#!/usr/bin/env bash

source "${HAKU_BIN_DIR:-$HOME/.local/bin}/haku_theme.sh" || exit 1
# Mutation belongs to theme_ctl; this renderer only reads canonical state.
if [[ $# -gt 0 ]]; then
    printf 'Usage: gen_style.sh\nUse theme_ctl.sh set-accent|set-font|set-size to change theme state.\n'
    [[ "${1:-}" == --help || "${1:-}" == -h ]] && exit 0
    exit 2
fi

hex_to_rgba() {
    local hex="${1#\#}"
    printf 'rgba(%sff)\n' "${hex,,}"
}

hex_to_rgb() {
    local hex="${1#\#}"
    printf 'rgb(%d, %d, %d)\n' $((16#${hex:0:2})) $((16#${hex:2:2})) $((16#${hex:4:2}))
}

hex_to_0x() {
    printf '0x%sff\n' "${1#\#}"
}

hex_to_rgba_alpha() {
    local hex="${1#\#}" alpha="${2:-0.4}"
    printf 'rgba(%d, %d, %d, %s)\n' $((16#${hex:0:2})) $((16#${hex:2:2})) $((16#${hex:4:2})) "$alpha"
}

ACCENT_RGBA="$(hex_to_rgba "$ACCENT_COLOR")"
ACCENT_RGB="$(hex_to_rgb "$ACCENT_COLOR")"
ACCENT_0X="$(hex_to_0x "$ACCENT_COLOR")"

ACCENT_DIM_ALPHA="${ACCENT_DIM_ALPHA:-0.8}"
ACCENT_DIM="$(hex_to_rgba_alpha "$ACCENT_COLOR" "$ACCENT_DIM_ALPHA")"

HIKAI_RENDER_DIR="$THEME_RENDER_DIR/hikai"
CLASSIC_RENDER_DIR="$THEME_RENDER_DIR/classic"
mkdir -p "$HIKAI_RENDER_DIR" "$CLASSIC_RENDER_DIR"

ACTIVE_BACKEND="classic"
if [[ -f "$(haku_state_path shell.backend)" ]]; then
    case "$(cat "$(haku_state_path shell.backend)" 2>/dev/null)" in
        hikai) ACTIVE_BACKEND="hikai" ;;
        classic) ACTIVE_BACKEND="classic" ;;
    esac
fi

publish_active() {
    local rel="$1"
    local dst="${2:-$THEME_RENDER_DIR/$rel}"
    local src="$THEME_RENDER_DIR/$ACTIVE_BACKEND/$rel"
    local tmp
    mkdir -p "$(dirname "$dst")"
    tmp=$(mktemp "${dst}.XXXXXX") || return 1
    if cp "$src" "$tmp" && mv -f "$tmp" "$dst"; then
        return 0
    fi
    rm -f "$tmp"
    return 1
}

render_colors() {
    cat > "$THEME_RENDER_DIR/colors.css" <<EOF
/* Generated by ~/.local/bin/gen_style.sh */
@define-color accent_color ${ACCENT_COLOR};
EOF
}

render_fonts() {
    cat > "$THEME_RENDER_DIR/fonts.css" <<EOF
/* Generated by ~/.local/bin/gen_style.sh */
* {
    font-family: "${FONT_FAMILY}";
    font-size: ${FONT_SIZE}px;
}
EOF
}

render_hyprland() {
    cat > "$THEME_RENDER_DIR/hyprland-style.conf" <<EOF
# Generated by ~/.local/bin/gen_style.sh
\$font_family = ${FONT_FAMILY}
\$font_size = ${FONT_SIZE}
\$accent_color = ${ACCENT_RGB}
EOF
    cat > "$HIKAI_RENDER_DIR/hyprland-style.lua" <<EOF
-- Generated by ~/.local/bin/gen_style.sh (mode: hikai)
return {
    font_family = "${FONT_FAMILY}",
    font_size = ${FONT_SIZE},
    border_color = "${ACCENT_RGBA}",
    apply = function()
    end,
}
EOF
    cat > "$CLASSIC_RENDER_DIR/hyprland-style.lua" <<EOF
-- Generated by ~/.local/bin/gen_style.sh (mode: classic)
return {
    font_family = "${FONT_FAMILY}",
    font_size = ${FONT_SIZE},
    border_color = "${ACCENT_RGBA}",
    apply = function()
        hl.config({
            decoration = {
                rounding = 0,
                rounding_power = 1,
                active_opacity = 1.0,
                inactive_opacity = 1.0,
                shadow = { enabled = false },
                blur = { enabled = false },
            },
        })
        if opacityCertainApps then opacityCertainApps:set_enabled(false) end
        if hakuSpaceOpacityRule then hakuSpaceOpacityRule:set_enabled(false) end
        if rofiAnimation then rofiAnimation:set_enabled(false) end
        hl.layer_rule({
            name = "rofi-classic",
            match = { namespace = "rofi" },
            no_anim = true,
            blur = false,
        })
        hl.layer_rule({
            name = "waybar-classic-opaque",
            match = { namespace = "waybar" },
            blur = false,
        })
        hl.window_rule({
            name = "classic-opaque-all",
            match = { class = ".*" },
            opacity = "1.0 override 1.0 override 1.0 override",
        })
    end,
}
EOF
    publish_active "hyprland-style.lua"
}

