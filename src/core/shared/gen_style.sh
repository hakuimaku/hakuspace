render_labwc() {
    [[ -f "$HAKU_BIN_DIR/classic_palette.py" ]] || return 0
    local rc_args=() rc_src=""
    if [[ -f "${THEME_LABWC_RC_TEMPLATE:-}" ]]; then
        rc_src="$THEME_LABWC_RC_TEMPLATE"
    elif [[ -f "${THEME_LABWC_RC:-}" && ! -L "$THEME_LABWC_RC" ]]; then
        rc_src="$THEME_LABWC_RC"
    fi
    if [[ -n "$rc_src" && -n "${THEME_LABWC_RC:-}" ]]; then
        rc_args=(--rc-template "$rc_src" --rc-out "$THEME_LABWC_RC" --font-family "$FONT_FAMILY" --font-size "$FONT_SIZE")
    fi
    python3 "$HAKU_BIN_DIR/classic_palette.py" render-labwc \
        --scheme "${CLASSIC_EFFECTIVE_SCHEME:-gray}" \
        --out-dir "$(dirname "$THEME_LABWC_OVERRIDE")" \
        "${rc_args[@]}" || return 1
}

render_quickshell() {
    if jq -n \
        --arg accentSeed "${ACCENT_SEED}" \
        --arg accentDark "${ACCENT_DARK}" \
        --arg accentLight "${ACCENT_LIGHT}" \
        --arg font "${FONT_FAMILY}" \
        --argjson fontSize "${FONT_SIZE}" \
        '{
            preset: "irunu",
            accentSeed: $accentSeed,
            accentDark: $accentDark,
            accentLight: $accentLight,
            font: $font,
            fontSize: $fontSize,
            border: "transparent",
            borderWidth: 0,
            gap: 4,
            pad: 12
        }' > "$THEME_RENDER_DIR/quickshell.json.tmp"; then
        mv "$THEME_RENDER_DIR/quickshell.json.tmp" "$THEME_RENDER_DIR/quickshell.json"
    fi
}
render_classic() {
    [[ -f "$HAKU_BIN_DIR/classic_palette.py" ]] || return 0
    local req_file eff_file requested previous effective scheme_accent
    req_file="$(haku_state_path theme.classic.palette)" || return 1
    eff_file="$(haku_state_path theme.classic.palette.effective)" || return 1
    requested="$(cat "$req_file" 2>/dev/null || printf 'auto')"
    previous="$(cat "$eff_file" 2>/dev/null || printf '')"
    effective="$(python3 "$HAKU_BIN_DIR/classic_palette.py" resolve \
        --seed "$ACCENT_SEED" --requested "$requested" --previous "$previous")" || return 1
    CLASSIC_EFFECTIVE_SCHEME="$effective"
    python3 "$HAKU_BIN_DIR/classic_palette.py" render \
        --scheme "$effective" --out-dir "$THEME_RENDER_DIR/classic" || return 1
    scheme_accent="$(sed -n 's/^@define-color select_bg \(#[0-9a-fA-F]\{6\}\);$/\1/p' "$CLASSIC_RENDER_DIR/palette.css" | head -n1)"
    if [[ -n "$scheme_accent" ]]; then
        CLASSIC_ACCENT="$scheme_accent"
        CLASSIC_ACCENT_RGBA="$(hex_to_rgba "$CLASSIC_ACCENT")"
        CLASSIC_ACCENT_0X="$(hex_to_0x "$CLASSIC_ACCENT")"
    fi
}

RENDERERS=(classic colors fonts hyprland rofi kitty btop newtab niri mango labwc quickshell)
for renderer in "${RENDERERS[@]}"; do
    "render_${renderer}"
done

echo "Generated theme files in: $THEME_RENDER_DIR"
echo "ACCENT_COLOR=$ACCENT_COLOR"
echo "FONT_FAMILY=$FONT_FAMILY"
echo "FONT_SIZE=$FONT_SIZE"
