#!/usr/bin/env bash

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
LIB_DIR="$SCRIPT_DIR"
[[ -f "$LIB_DIR/haku_theme.sh" ]] || LIB_DIR="$SCRIPT_DIR/../lib"
source "$LIB_DIR/haku_theme.sh" || exit 1
# Mutation belongs to theme_ctl; this renderer only reads canonical state.
if [[ $# -gt 0 ]]; then
    printf 'Usage: gen_style.sh\nUse theme_ctl.sh set-accent|set-font|set-size to change theme state.\n'
    [[ "${1:-}" == --help || "${1:-}" == -h ]] && exit 0
    exit 2
fi

hex_to_rgba() {
    local hex="${1#\#}"
    printf 'rgba(%sff)\n' "${hex,,}"
}

hex_to_rgb() {
    local hex="${1#\#}"
    printf 'rgb(%d, %d, %d)\n' $((16#${hex:0:2})) $((16#${hex:2:2})) $((16#${hex:4:2}))
}

hex_to_0x() {
    printf '0x%sff\n' "${1#\#}"
}

hex_to_rgba_alpha() {
    local hex="${1#\#}" alpha="${2:-0.4}"
    printf 'rgba(%d, %d, %d, %s)\n' $((16#${hex:0:2})) $((16#${hex:2:2})) $((16#${hex:4:2})) "$alpha"
}

ACCENT_RGBA="$(hex_to_rgba "$ACCENT_COLOR")"
ACCENT_RGB="$(hex_to_rgb "$ACCENT_COLOR")"
ACCENT_0X="$(hex_to_0x "$ACCENT_COLOR")"

ACCENT_DIM_ALPHA="${ACCENT_DIM_ALPHA:-0.8}"
ACCENT_DIM="$(hex_to_rgba_alpha "$ACCENT_COLOR" "$ACCENT_DIM_ALPHA")"

render_colors() {
    cat > "$THEME_RENDER_DIR/colors.css" <<EOF
/* Generated by ~/.local/bin/gen_style.sh */
@define-color accent_color ${ACCENT_COLOR};
EOF
}

render_fonts() {
    cat > "$THEME_RENDER_DIR/fonts.css" <<EOF
/* Generated by ~/.local/bin/gen_style.sh */
* {
    font-family: "${FONT_FAMILY}";
    font-size: ${FONT_SIZE}px;
}
EOF
}

render_hyprland() {
    cat > "$THEME_RENDER_DIR/hyprland-style.conf" <<EOF
# Generated by ~/.local/bin/gen_style.sh
\$font_family = ${FONT_FAMILY}
\$font_size = ${FONT_SIZE}
\$accent_color = ${ACCENT_RGB}
EOF
    cat > "$THEME_RENDER_DIR/hyprland-style.lua" <<EOF
-- Generated by ~/.local/bin/gen_style.sh
return {
    font_family = "${FONT_FAMILY}",
    font_size = ${FONT_SIZE},
    border_color = "${ACCENT_RGBA}",
}
EOF
}

render_rofi() {
    cat > "$THEME_RENDER_DIR/rofi-style.rasi" <<EOF
/* Generated by ~/.local/bin/gen_style.sh */
* {
    accent: ${ACCENT_COLOR};
    accent-dim: ${ACCENT_DIM};
    font: "${FONT_FAMILY} ${FONT_SIZE}";
}
EOF
    cat > "$THEME_RENDER_DIR/rofi-wallpaper-select.rasi" <<EOF
/* Generated by ~/.local/bin/gen_style.sh */
* {
    font: "${FONT_FAMILY} 11";
}
EOF
}

render_kitty() {
    cat > "$THEME_RENDER_DIR/kitty-style.conf" <<EOF
# Generated by ~/.local/bin/gen_style.sh
font_family      family="${FONT_FAMILY}"
font_size        ${FONT_SIZE}
foreground ${ACCENT_COLOR}
color7 ${ACCENT_COLOR}
color15 ${ACCENT_COLOR}
EOF
}

render_btop() {
    mkdir -p "$THEME_BTOP_DIR"
    cat > "$THEME_BTOP_DIR/HakuBtop.theme" <<EOF
# Generated by ~/.local/bin/gen_style.sh
theme[main_bg]="#000000"
theme[main_fg]="#c0c0c0"
theme[title]="${ACCENT_COLOR}"
theme[hi_fg]="${ACCENT_COLOR}"
theme[selected_fg]="${ACCENT_COLOR}"
theme[proc_misc]="${ACCENT_COLOR}"
theme[cpu_box]="${ACCENT_COLOR}"
theme[mem_box]="${ACCENT_COLOR}"
theme[net_box]="${ACCENT_COLOR}"
theme[disk_box]="${ACCENT_COLOR}"
EOF
}

render_newtab() {
    cat > "$THEME_RENDER_DIR/newtab.css" <<EOF
/* Generated by ~/.local/bin/gen_style.sh */
:root {
    --accent_color: ${ACCENT_COLOR};
    --font_family: "${FONT_FAMILY}";
}
EOF
}

render_niri() {
    cat > "$THEME_RENDER_DIR/niri-style.kdl" <<EOF
// Generated by ~/.local/bin/gen_style.sh
layout {
    focus-ring {
        active-color "${ACCENT_COLOR}"
    }
}
EOF
}

render_mango() {
    cat > "$THEME_RENDER_DIR/mangowm-style.conf" <<EOF
# Generated by ~/.local/bin/gen_style.sh
focus_color=${ACCENT_0X}
maximized_screen_color=${ACCENT_0X}
scratchpad_color=${ACCENT_0X}
global_color=${ACCENT_0X}
overlay_color=${ACCENT_0X}
EOF
}

render_labwc() {
    if [[ -f "$THEME_LABWC_OVERRIDE" ]]; then
        local theme_block
        theme_block="# BEGIN GENERATED THEME
window.active.border.color: ${ACCENT_COLOR}
window.inactive.border.color: #000000
window.active.label.text.color: ${ACCENT_COLOR}
window.inactive.label.text.color: ${ACCENT_COLOR}
window.active.button.unpressed.image.color: ${ACCENT_COLOR}
window.inactive.button.unpressed.image.color: ${ACCENT_COLOR}
menu.items.active.bg: ${ACCENT_COLOR}
menu.items.text.color: ${ACCENT_COLOR}
menu.items.active.bg.color: ${ACCENT_COLOR}
menu.title.bg.color: ${ACCENT_COLOR}
osd.border.color: ${ACCENT_COLOR}
osd.label.text.color: ${ACCENT_COLOR}
osd.window-switcher.style-classic.item.active.border.color: ${ACCENT_COLOR}
osd.window-switcher.style-thumbnail.item.active.border.color: ${ACCENT_COLOR}
# END GENERATED THEME"
        if grep -q "# BEGIN GENERATED THEME" "$THEME_LABWC_OVERRIDE"; then
            awk -v block="$theme_block" '/# BEGIN GENERATED THEME/ { print block; skip=1; next } /# END GENERATED THEME/ { skip=0; next } !skip { print }' \
                "$THEME_LABWC_OVERRIDE" > "${THEME_LABWC_OVERRIDE}.tmp" && cat "${THEME_LABWC_OVERRIDE}.tmp" > "$THEME_LABWC_OVERRIDE" && rm -f "${THEME_LABWC_OVERRIDE}.tmp"
        fi
    fi

    if [[ -f "$THEME_LABWC_RC" ]]; then
        local labwc_font_size=$((FONT_SIZE - 2))
        (( labwc_font_size < 8 )) && labwc_font_size=8
        export GEN_FONT_BLOCK="        <!-- BEGIN GENERATED FONTS -->
            <font place=\"ActiveWindow\"><name>${FONT_FAMILY}</name><size>${labwc_font_size}</size><slant>normal</slant><weight>normal</weight></font>
            <font place=\"InactiveWindow\"><name>${FONT_FAMILY}</name><size>${labwc_font_size}</size><slant>normal</slant><weight>normal</weight></font>
            <font place=\"MenuHeader\"><name>${FONT_FAMILY}</name><size>${labwc_font_size}</size><slant>normal</slant><weight>normal</weight></font>
            <font place=\"MenuItem\"><name>${FONT_FAMILY}</name><size>${labwc_font_size}</size><slant>normal</slant><weight>normal</weight></font>
            <font place=\"OnScreenDisplay\"><name>${FONT_FAMILY}</name><size>${labwc_font_size}</size><slant>normal</slant><weight>normal</weight></font>
            <!-- END GENERATED FONTS -->"
        if grep -q "<!-- BEGIN GENERATED FONTS -->" "$THEME_LABWC_RC"; then
            awk '/<!-- BEGIN GENERATED FONTS -->/ { print ENVIRON["GEN_FONT_BLOCK"]; skip=1; next } /<!-- END GENERATED FONTS -->/ { skip=0; next } !skip { print }' \
                "$THEME_LABWC_RC" > "${THEME_LABWC_RC}.tmp" && cat "${THEME_LABWC_RC}.tmp" > "$THEME_LABWC_RC" && rm -f "${THEME_LABWC_RC}.tmp"
        fi
    fi
}

render_quickshell() {
    if jq -n \
        --arg accent "${ACCENT_COLOR}" \
        --arg font "${FONT_FAMILY}" \
        --argjson fontSize "${FONT_SIZE}" \
        --arg fgDim "${ACCENT_DIM}" \
        '{
            preset: "irunu",
            accent: $accent,
            font: $font,
            fontSize: $fontSize,
            surfaceHi: $accent,
            border: "transparent",
            fg: $accent,
            fgDim: $fgDim,
            fgMuted: "rgba(255, 255, 255, 0.5)",
            borderWidth: 0,
            gap: 4,
            pad: 12
        }' > "$THEME_RENDER_DIR/quickshell.json.tmp"; then
        mv "$THEME_RENDER_DIR/quickshell.json.tmp" "$THEME_RENDER_DIR/quickshell.json"
    fi
}
RENDERERS=(colors fonts hyprland rofi kitty btop newtab niri mango labwc quickshell)
for renderer in "${RENDERERS[@]}"; do
    "render_${renderer}"
done

echo "Generated theme files in: $THEME_RENDER_DIR"
echo "ACCENT_COLOR=$ACCENT_COLOR"
echo "FONT_FAMILY=$FONT_FAMILY"
echo "FONT_SIZE=$FONT_SIZE"
