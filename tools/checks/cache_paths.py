#!/usr/bin/env python3
"""Reject cache paths outside the shared namespace in production sources."""
from pathlib import Path
import re
import subprocess
import sys

# Exceptions name the exact fallback, legacy migration, or shared desktop read.
ROOT = Path(__file__).resolve().parents[2]
ALLOWED = {
    "src/core/lib/haku_cache.sh": {'HAKUSPACE_CACHE_DIR="${XDG_CACHE_HOME:-$HOME/.cache}/hakuspace"'},
    "src/core/lib/haku_cache.py": {'return Path(os.environ.get("XDG_CACHE_HOME") or Path.home() / ".cache") / "hakuspace"'},
    "src/core/state/haku_state_migrate.py": {'legacy_root = Path.home() / ".cache"'},
    "src/core/app/desktop-icons/desktop_icons.py": {
        "('large', '~/.cache/thumbnails/large'),", "('normal', '~/.cache/thumbnails/normal'),"},
    "src/core/util/clean.sh": {
        'echo "This will remove all files in ~/.cache and clear journal logs older than 2 weeks."',
        'rm -rf ~/.cache/*'},
}
CACHE_PATH = re.compile(r'''(?:(?<![\w.-])\.cache(?:/|["'])|XDG_CACHE_HOME|current_wallpaper|taskbar_icons|taskbar_icon_cache)''')


def check_text(path, source):
    """Flag new path policy while allowing documentation and isolated test environments."""
    if not path.startswith(("src/", "scripts/")):
        return []
    return [f"{path}:{number}: use haku_cache helpers for HakuSpace cache paths"
            for number, line in enumerate(source.splitlines(), 1)
            if CACHE_PATH.search(line) and line.strip() not in ALLOWED.get(path, set())
            and not line.lstrip().startswith(("#", "//", "/*"))
            and not (path == "src/core/state/haku_state_migrate.py" and '"current_wallpaper"' in line)]


def main():
    """Audit tracked and newly added production files without scanning generated bytecode."""
    paths = subprocess.check_output(["git", "ls-files", "--cached", "--others", "--exclude-standard", "-z"], cwd=ROOT).decode().split("\0")
    errors = []
    for name in sorted(set(paths)):
        path = ROOT / name
        if not name.startswith(("src/", "scripts/")) or not path.is_file() or path.is_symlink():
            continue
        try:
            errors.extend(check_text(name, path.read_text()))
        except UnicodeError:
            continue
    if errors:
        print("\n".join(errors), file=sys.stderr)
        return 1
    print("Cache path contract: PASS")
    return 0


if __name__ == "__main__":
    sys.exit(main())
