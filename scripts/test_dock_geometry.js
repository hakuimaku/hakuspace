const assert = require('node:assert/strict')
const fs = require('node:fs')
const vm = require('node:vm')
// Exercise output-local activation and the full morph/hover safe envelope.
const geometry = vm.createContext({})
vm.runInContext(fs.readFileSync('src/home/.config/quickshell/hakuspace/components/dock/DockGeometry.js', 'utf8'), geometry)
const json = value => JSON.parse(JSON.stringify(value))
for (const width of [640, 1920, 2560]) {
    const trigger = geometry.trigger(width, 220)
    assert.equal(trigger.width, width * 0.2)
    assert.equal(trigger.x, width * 0.4)
    assert.equal(trigger.y + trigger.height, 220)
    const safe = geometry.envelope(width, 220, 400, 80, 440, 75, 18)
    assert.equal(safe.width, 440)
    assert.equal(safe.height, 98)
    assert.equal(safe.x + safe.width / 2, width / 2)
    assert.equal(safe.y + safe.height, 220)
}
assert.deepEqual(json(geometry.envelope(320, 100, 800, 90, 400, 120, 18)), {x: 0, y: 0, width: 320, height: 100})
// Lift peaks at the slot center and decays symmetrically across neighboring slots.
assert.equal(geometry.hoverInfluence(NaN, 32, 160), 0)
assert.equal(geometry.hoverInfluence(32, 32, 0), 0)
assert.equal(geometry.hoverInfluence(32, 32, 160), 1)
assert.equal(geometry.hoverInfluence(192, 32, 160), 0)
assert.equal(geometry.hoverInfluence(-128, 32, 160), 0)
assert.equal(geometry.hoverInfluence(-36, 32, 160), geometry.hoverInfluence(100, 32, 160))
assert.ok(geometry.hoverInfluence(100, 32, 160) > geometry.hoverInfluence(168, 32, 160))
console.log('Dock geometry checks passed')
